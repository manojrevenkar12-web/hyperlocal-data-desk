"""Writes the results block of README.md from reports/dev.json and reports/heldout.json. Never edit it by hand."""

from __future__ import annotations

import json
import math
from pathlib import Path
from typing import Any

START = "<!-- results:start -->"
END = "<!-- results:end -->"


def _n(x: float, d: int = 1) -> str:
    if x is None or (isinstance(x, float) and math.isnan(x)):
        return "–"
    return f"{x:,.{d}f}"


def _ci(s: dict[str, float], d: int = 1, scale: float = 1.0) -> str:
    v = _n(s["value"] * scale, d)
    if s["lo"] == s["hi"]:
        return v
    return f"{v} <sub>{_n(s['lo'] * scale, d)}–{_n(s['hi'] * scale, d)}</sub>"


def _clock(minute: float) -> str:
    if minute is None or (isinstance(minute, float) and math.isnan(minute)):
        return "–"
    m = round(minute)
    return f"{18 + m // 60:02d}:{m % 60:02d}"


def _table(designs: list[dict[str, Any]]) -> str:
    out = (
        "| Design | Stories in the top 8 per release | Stories from strong leads | Strong leads that are stories "
        "| Reporter hours per story | Texts with a wrong number per 1,000 | Lead notes with a wrong number per 100 "
        "| Broken files published per season |\n"
    )
    out += "|---|---|---|---|---|---|---|---|\n"
    for d in designs:
        s = d["stats"]
        name = f"**{d['label']}**" if d["name"] == "desk" else d["label"]
        out += (
            f"| {name} | {_ci(s['budget_found'])} | {_ci(s['stories_found'])} | {_ci(s['precision'], 0, 100)}% | "
            f"{_ci(s['hours_per_story'])} | {_ci(s['wrong_texts_per_1000'])} | {_ci(s['wrong_notes_per_100'])} | "
            f"{_ci(s['broken_published'])} |\n"
        )
    return out


def _night(r: dict[str, Any]) -> str:
    out = (
        "| Election night | Districts called for the wrong party, per night | Median call | Municipality-minutes showing a wrong result |\n"
    )
    out += "|---|---|---|---|\n"
    for d in r["night"]:
        s = d["stats"]
        name = f"**{d['label']}**" if d["name"] == "desk" else d["label"]
        minutes = _n(s["wrong_figures_minutes"]["value"], 0)
        out += f"| {name} | {_ci(s['wrong_calls'], 2)} | {_clock(s['median_call_minute']['value'])} | {minutes} |\n"
    return out


def _gates(r: dict[str, Any]) -> str:
    ok = sum(1 for g in r["gates"] if g["pass"])
    out = f"**{ok} of {len(r['gates'])} gates pass.**\n\n| Gate | Rule | Got | |\n|---|---|---|---|\n"
    for g in r["gates"]:
        out += f"| {g['name']} | {g['rule']} {g['want']} | {g['got']} | {'pass' if g['pass'] else '**fail**'} |\n"
    return out


def _tiles(r: dict[str, Any]) -> str:
    v = {d["name"]: {k: s["value"] for k, s in d["stats"].items()} for d in r["designs"]}
    nv = {d["name"]: {k: s["value"] for k, s in d["stats"].items()} for d in r["night"]}
    best = max(v["spreadsheet"]["budget_found"], v["model_alone"]["budget_found"])

    def tile(big: str, label: str) -> str:
        return f'<td align="center" width="25%"><h3>{big}</h3>{label}</td>'

    return (
        "<table><tr>"
        + "".join(
            [
                tile(
                    f"{v['desk']['budget_found'] / max(best, 1e-9):.1f}×",
                    "stories in the top 8, against the better of a spreadsheet and a model alone",
                ),
                tile(
                    f"{100 * v['desk']['precision']:.0f}% vs {100 * v['spreadsheet']['precision']:.0f}%",
                    "strong leads that are real stories: desk vs spreadsheet",
                ),
                tile(
                    f"{_n(v['desk']['wrong_texts_per_1000'])} vs {_n(v['model_alone']['wrong_texts_per_1000'])}",
                    "municipal texts with a wrong number per 1,000: desk vs a model alone",
                ),
                tile(
                    f"{_n(nv['desk']['wrong_calls'], 2)} vs {_n(nv['counted_half']['wrong_calls'], 2)}",
                    "districts called wrong per election night: desk vs calling at half counted",
                ),
            ]
        )
        + "</tr></table>\n"
    )


def _block(r: dict[str, Any], title: str, note: str) -> str:
    main = [d for d in r["designs"] if not d["ablation"]]
    abl = [d for d in r["designs"] if d["ablation"] or d["name"] == "desk"]
    return (
        f"### {title}\n\n{note}\n\n{_tiles(r)}\n{_gates(r)}\n{_table(main)}\nThe desk with one piece taken away:\n\n{_table(abl)}\n"
        f"{_night(r)}\n"
    )


def readme(root: Path) -> None:
    dev = json.loads((root / "reports" / "dev.json").read_text(encoding="utf-8"))
    hp = root / "reports" / "heldout.json"
    held = json.loads(hp.read_text(encoding="utf-8")) if hp.exists() else None
    out = f"{START}\n_Generated by `uv run desk readme` from `reports/dev.json` and `reports/heldout.json`. Do not edit by hand._\n\n"
    out += (
        f"Each world is {len(dev['seeds'])} seeds of {dev['quarters']} quarters for {dev['municipalities']:,} municipalities and four "
        "sources, plus one election night per seed. Every design reads the same files with the same model mistakes. Small numbers are 95% "
        "bootstrap intervals over seeds. A strong lead costs a reporter 45 minutes; the top 8 per release is the desk's capacity, "
        "strong leads and watch list together.\n\n"
    )
    out += (
        _block(
            held,
            "Held-out world (ran once)",
            f"Seeds {held['seeds'][0]}–{held['seeds'][-1]}: other municipalities, mergers on 1 January 2027, lumpier counts, more "
            "stories and drift, and file layouts, unit labels and kinds of drift the dev world never used (swapped columns, comma "
            "separators).",
        )
        if held
        else "### Held-out world\n\nNot run yet. `uv run desk study --world heldout` runs it once and locks it.\n\n"
    )
    out += _block(dev, "Dev world", f"Seeds {dev['seeds'][0]}–{dev['seeds'][-1]}. Every rule and threshold of the desk was tuned here.")
    out += END
    path = root / "README.md"
    text = path.read_text(encoding="utf-8")
    i, j = text.find(START), text.find(END)
    if i < 0 or j < i:
        raise ValueError(f"README.md has no {START} … {END} block")
    path.write_text(text[:i] + out + text[j + len(END) :], encoding="utf-8")
